import Foundation

/// Accessibility Identifiers for all SwiftUI generic UI Components
extension AccessibilityIdentifiers {
    enum StandardTextField {
        static let placeholderText = "standardTextFieldPlaceholderText"
        static let inputField = "standardTextFieldInputField"
        static let infoText = "standardTextFieldInfoText"
    }

    enum StandardModalToolbar {
        static let closeImage = "StandardModalToolbarCloseImage"
    }
}
